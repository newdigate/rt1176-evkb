#!/bin/bash
# Regenerates the probe's test clips and ../clips.h.  Needs ffmpeg, a host C++
# compiler and ~/Development/audio-codecs (or $AUDIO_CODECS) built with CMake.
#
# One 8 s, 44.1 kHz stereo clip -- a 120 BPM click (a 20 ms 1 kHz burst every
# 0.5 s) over quiet pink noise -- as FLAC and as 128 kbps MP3 with an ID3v2
# tag (8 s each), its first 2 s as 16-bit WAV and AIFF, and its first 0.5 s as
# 24-bit WAV.  clips.h lists each file with the frame count and the FNV-1a of the 16-bit
# PCM that audio-codecs produces from it ON THE HOST, so the board is checked
# against the host bit for bit.
set -e
cd "$(dirname "$0")"
AC=${AUDIO_CODECS:-$HOME/Development/audio-codecs}
FF="ffmpeg -hide_banner -loglevel error -y"
$FF -f lavfi -i "anoisesrc=color=pink:amplitude=0.02:sample_rate=44100:duration=8:seed=7" \
    -f lavfi -i "sine=frequency=1000:sample_rate=44100:duration=8" \
    -filter_complex "[1:a]volume='if(lt(mod(t,0.5),0.02),0.8,0)':eval=frame[c];[0:a][c]amix=inputs=2:normalize=0,pan=stereo|c0=c0|c1=0.8*c0[o]" \
    -map "[o]" -c:a pcm_s16le -bitexact click.wav
$FF -i click.wav -c:a flac -bitexact click.flac
$FF -i click.wav -c:a libmp3lame -b:a 128k -id3v2_version 3 -metadata title="click 120" click.mp3
# The PCM containers are cut to 2 s (and the 24-bit one to 0.5 s) to keep the image small:
# FLAC carries the full 8 s that the spectrum and tempo stages need.
$FF -i click.wav -t 2 -c:a pcm_s16le -bitexact short.wav
$FF -i click.wav -t 2 -c:a pcm_s16be -bitexact short.aiff
$FF -i click.wav -t 0.5 -c:a pcm_s24le -bitexact short24.wav
c++ -std=c++17 -O2 -I"$AC/include" -I"$AC" -I.. -o host_decode host_decode.cpp \
    "$AC"/build/libaudio_codecs_wav.a "$AC"/build/libaudio_codecs_aiff.a "$AC"/build/libaudio_codecs_flac.a \
    "$AC"/build/libaudio_codecs_mp3.a "$AC"/build/libaudio_codecs_core.a
c++ -std=c++17 -O2 -I"$AC/include" -I"$AC" -I.. -o host_analyse host_analyse.cpp \
    "$AC"/build/libaudio_codecs_flac.a "$AC"/build/libaudio_codecs_tempo.a "$AC"/build/libaudio_codecs_spectrum.a \
    "$AC"/build/libaudio_codecs_preview.a "$AC"/build/libaudio_codecs_core.a
FILES="short.wav short.aiff click.flac click.mp3 short24.wav"
{
  echo "/* clips.h -- GENERATED by clips/make_clips.sh; do not edit."
  echo " * The files themselves are linked in by clips_data.S (.incbin). */"
  echo "#pragma once"
  echo "#include <stdint.h>"
  echo "#include <stddef.h>"
  for f in $FILES; do n=$(echo "$f" | tr '.' '_'); echo "extern \"C\" const uint8_t clip_${n}[]; extern \"C\" const uint8_t clip_${n}_end[];"; done
  echo "struct ClipInfo { const char *name; const char *fmt; const uint8_t *data; const uint8_t *end; uint32_t rate; uint8_t channels; uint32_t frames; uint32_t fnv; };"
  echo "static const ClipInfo clips[] = {"
  for f in $FILES; do n=$(echo "$f" | tr '.' '_'); ./host_decode "$f" "$n"; done
  echo "};"
  echo "/* MP3: window sums of |sample| and a 1024-frame excerpt of the host's decode. */"
  ./host_decode click.mp3 click_mp3 /dev/null mp3_sig.tmp > /dev/null; cat mp3_sig.tmp; rm -f mp3_sig.tmp
  echo "/* Spectrum and tempo of click.flac's PCM on the host: the board must reproduce these. */"
  ./host_analyse click.flac 0 defines
} > ../clips.h
{
  echo "/* clips_data.S -- GENERATED by clips/make_clips.sh; do not edit. */"
  echo "    .section .progmem.clips, \"a\", %progbits"
  for f in $FILES; do n=$(echo "$f" | tr '.' '_')
    echo "    .balign 4"; echo "    .global clip_${n}"; echo "clip_${n}:"; echo "    .incbin \"clips/${f}\""
    echo "    .global clip_${n}_end"; echo "clip_${n}_end:"
  done
} > ../clips_data.S
rm -f click.wav
ls -l $FILES | awk '{s+=$5; print $5, $9} END{print s, "total"}'
grep -A6 "static const ClipInfo clips" ../clips.h
