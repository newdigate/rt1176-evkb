#!/usr/bin/env python3
"""Regenerates touch_script.txt for the dj_deck gate.

One instant per line.  The model publishes the next instant only after the
firmware has read the previous one, at most one per 20 ms
(IMXRT_GT911_STEP_MS): a wait is counted in touch reads, so it is at least
20 ms per instant and longer when the frame rate is lower.  'P a b' presses at
a % of the PHYSICAL panel's width and b % of its height.  The display is
presented CW90, so a logical (lx, ly) on the 1280x720 canvas is physical
(719 - ly, lx).  Targets are the centres of the controls in ui_deck.cpp and
ui_browser.cpp; every one is far larger than the 1 % grid.
"""
LEAD, GAP, LOAD = 50, 40, 400   # LOAD: the clip loads in ~3 s; 400 reads are at least 8 s
lines = []
def rest(n): lines.extend(['R'] * n)
def tap(lx, ly, hold=4):
    a = round((719 - ly) * 100 / 720); b = round(lx * 100 / 1280)
    lines.extend([f'P {a} {b}'] * hold)
ROW = lambda r: (16 + 300, 96 + r * 88 + 40)
FILES, CUE, PLAY, ZIN = (104, 616), (472, 616), (692, 616), (1100, 616)
rest(LEAD)
tap(*FILES);  rest(GAP)        # browser opens at /        -> BROWSE dir=/ n=1
tap(*ROW(0)); rest(GAP)        # "music"                   -> BROWSE dir=/music n=2
tap(*ROW(2)); rest(LOAD)       # "..", "sub", "click.wav"  -> BROWSE_PICK, the load
tap(*PLAY);   rest(GAP)        # UI_PLAY=1
tap(*ZIN);    rest(GAP // 2)   # UI_ZOOM halves
tap(*ZIN);    rest(GAP)        # UI_ZOOM halves again
tap(*PLAY);   rest(GAP // 2)   # UI_PLAY=0
tap(*CUE);    rest(GAP)        # UI_CUE=SetCue
with open(__file__.rsplit('/', 1)[0] + '/touch_script.txt', 'w') as f:
    f.write("# dj_deck gate script -- GENERATED by gen_touch_script.py, never hand-counted.\n")
    f.write('\n'.join(lines) + '\n')
print(len(lines), "instants")
