#!/usr/bin/env python3
"""Regenerates touch_script.txt and prints the values run_qemu.sh expects.

One instant per line, 20 ms apart (IMXRT_GT911_STEP_MS).  'P a b' presses at
a % of the PHYSICAL panel's width and b % of its height; the QEMU model
computes res*pct/100 in integers.  The display is presented CW90, so a logical
(lx, ly) on the 1280x720 canvas is physical (719 - ly, lx).  Because of the
1 % grid, every logical point below is first snapped to what the model will
actually deliver, and the expectations are computed from the snapped points.
"""
LEAD, GAP = 500, 60          # instants before the first gesture, and between gestures
WX, WY, WW, LANE_H, GAP_H, RAIL_H = 16, 96, 1120, 336, 8, 64
TOTAL, ZOOM, POS = 15876000, 2048, 7938000

def snap(lx, ly):
    a = round((719 - ly) * 100 / 720); b = round(lx * 100 / 1280)
    return a, b, 1280 * b // 100, 719 - 720 * a // 100       # pct_x, pct_y, logical x, logical y

lines, notes = [], []
def rest(n): lines.extend(['R'] * n)
def press(lx, ly, hold=3):
    a, b, sx, sy = snap(lx, ly)
    lines.extend([f'P {a} {b}'] * hold)
    return sx, sy

lane_y = WY + LANE_H // 2
rail_y = WY + LANE_H + GAP_H + RAIL_H // 2
def lane_drag(tag):
    xs = [press(lx, lane_y)[0] for lx in (576, 601, 627, 652, 678)]
    rest(GAP)
    notes.append(f'{tag}_dx={xs[-1] - xs[0]}')
    return xs[-1] - xs[0]

rest(LEAD)
dx = lane_drag('grab')                                         # 1: tracking on -> GRAB_BEGIN / MOVE / END
notes.append(f'grab_begin={POS}'); notes.append(f'grab_last={POS - dx * ZOOM}')
sx, sy = press(WX + WW // 4, rail_y, hold=4); rest(GAP)        # 2: rail tap -> SEEK
notes.append(f'seek={(sx - WX) * TOTAL // WW}')
dx = lane_drag('scroll')                                       # 3: tracking off -> the view scrolls, no event
notes.append(f'scroll_delta={-dx * ZOOM}')
sx, sy = press(WX + WW - 10, lane_y, hold=4); rest(GAP)        # 4: catch-up chevron -> TRACK_REQUEST
notes.append(f'chevron_at={sx - WX},{sy - WY}')
press(576, lane_y, hold=40); rest(GAP)                         # 5: long press; the test injects PRESS_LOST mid-way
lane_drag('cleared')                                           # 6: no track -> no events
press(WX + WW // 4, rail_y, hold=4); rest(GAP)
press(576, lane_y, hold=40); rest(GAP)                         # 7: long press; the test calls set_tables() mid-way
press(576, lane_y, hold=40); rest(GAP)                         # 8: long press; the test deletes the widget mid-way
rest(50)

open(__file__.rsplit('/', 1)[0] + '/touch_script.txt', 'w').write(
    '# synthui_waveform_test touch script -- GENERATED by gen_touch_script.py, never hand-edited.\n'
    + '\n'.join(lines) + '\n')
print(' '.join(notes), f'instants={len(lines)}')
